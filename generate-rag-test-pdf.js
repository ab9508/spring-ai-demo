// ============ 工具函数 ============
function title(text) {
  doc.fontSize(22).text(text, { align: 'center' });
  doc.moveDown(0.3);
  doc.fontSize(10).fillColor('#666666').text('文档版本：v1.0 | 生成日期：2026-04-30 | 用途：RAG检索质量测试', { align: 'center' });
  doc.fillColor('#000000');
  doc.moveDown(1.5);
  // 分隔线
  doc.moveTo(55, doc.y).lineTo(540, doc.y).stroke('#cccccc');
  doc.moveDown(1);
}

function h1(text) {
  checkPage(60);
  doc.moveDown(0.5);
  doc.fontSize(16).fillColor('#1a5276').text(text);
  doc.fillColor('#000000');
  doc.moveDown(0.3);
}

function h2(text) {
  checkPage(40);
  doc.moveDown(0.3);
  doc.fontSize(13).fillColor('#2c3e50').text(text);
  doc.fillColor('#000000');
  doc.moveDown(0.2);
}

function para(text) {
  doc.fontSize(11).text(text, { lineGap: 5, align: 'justify' });
  doc.moveDown(0.5);
}

function bullet(text) {
  doc.fontSize(11).text('  • ' + text, { lineGap: 4, indent: 15 });
  doc.moveDown(0.15);
}

function checkPage(need) {
  if (doc.y > 750 - need) doc.addPage();
}

